# PR2 taxonomy lookup
ranks18 <- c("Domain", "Supergroup", "Division", "Subdivision", "Class", "Order", "Family", "Genus", "Species")
pr2_tax <- pr2 %>% transmute(sseqid = pr2_accession, across(all_of(tolower(ranks18)))) %>% rename_with(str_to_title, all_of(tolower(ranks18)))

# 26545 original sequences -> 19433 are likely eukaryotes, out of which most (18044) have query coverage 100% and similarity ≥80%
# hits_pr2_filt$seq and conf_blast_18S$seqis are very similar (0.05% dif-ce), the latter resulting from cleaning using BLASTing against NCBI

# qcovhsp = 100 -> 18014 (qcovs = 100 and qcovus = 100, the same reuslt as for qcov = (qend - qstart + 1) / nchar(seq) * 100, but rounded up)
# qcovus = 100 -> 18018  (qcovs = 100 here but qcovhsp could be <100)
# qcovs = 100 -> 18041   (qcovus and qcovhsp could be <100)
# none of query coverages ever exceed 100

ranks18_eff <- c("Genus", "Family", "Order", "Class", "Subdivision", "Division", "Supergroup")
collapse_cols <- c("sseqid", "sstart", "send", "Species")

hits_pr2_filt <- hits_pr2 %>% left_join(pr2_tax, by = "sseqid") %>% filter(qcovhsp == 100, pident >= 80) %>% # add taxonomy and remove low quality alignments
  filter(bitscore == max(bitscore), .by = qseqid) %>%                    # highest bitscore per qseqid
  filter(pident   == max(pident), .by = qseqid) %>%                      # highest identity among those
  filter(mismatch == min(mismatch), .by = qseqid) %>%                    # fewest mismatches
  filter(gapopen  == min(gapopen), .by = qseqid) %>%                     # fewest gap openings
  rowwise() %>%                     # for each query, report all hits w/ the best bit score -> switch to by-row
  mutate(eff_idx = {v <- c_across(all_of(ranks18_eff)); nonX <- which(!str_detect(v, "_X")); if (length(nonX)) nonX[1] else length(v)},
         eff_tax = {v <- c_across(all_of(ranks18_eff)); v[eff_idx]}) %>% ungroup() %>%  # for each as-t, report the best/lowest known level and the name there
  group_by(qseqid) %>% add_count(eff_tax, name = "tax_n") %>%                      # for each query, get the frequency of the names sharing the best bit score
  arrange(eff_idx, desc(tax_n), eff_tax, .by_group = TRUE) %>% mutate(best_tax = eff_tax[1]) %>% # report the best tax. as-t.: lowest known rank + most freq-t
  ungroup() %>% filter(eff_tax == best_tax, Domain == "Eukaryota") %>% group_by(qseqid) %>%    # leave only euks and their best as-t -> regroup by query again
  summarise(across(all_of(collapse_cols), ~ paste(unique(.x), collapse = "; ")), across(!all_of(collapse_cols), ~ .x[1]), .groups = "drop")    # collapse info

